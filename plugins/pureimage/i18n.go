func resolveLang(_ string) string {
	return string(i18n.Current())
}

func tr(_ string, key string) string {
	zh := texts["zh-CN"][key]
	en := texts["en-US"][key]
	switch {
	case zh != "" && en != "":
		return i18n.S(zh, en)
	case en != "":
		return en
	case zh != "":
		return zh
	default:
		return key
	}
}
